package com.schoollink.people.internal;

import com.schoollink.TestcontainersConfiguration;
import com.schoollink.people.UserAccounts;
import com.schoollink.testsupport.TestWorld;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.oauth2.jwt.JwtEncoder;
import org.springframework.transaction.annotation.Transactional;

import static com.schoollink.testsupport.Actor.DM_1;
import static org.assertj.core.api.Assertions.assertThat;

/** UC-D9: the name printed on the report ("generated by"), within one school (NFR-8). Generated data only. */
@SpringBootTest
@Import(TestcontainersConfiguration.class)
@Transactional
class UserFullNameTests {

	@Autowired
	UserAccounts accounts;

	@Autowired
	JdbcTemplate jdbc;

	@Autowired
	JwtEncoder encoder;

	TestWorld world;

	@BeforeEach
	void createWorld() {
		world = TestWorld.create(jdbc, encoder);
	}

	@Test
	void fullNameIsFirstThenLastName() {
		UUID dm = world.user(DM_1);
		jdbc.update("UPDATE app_user SET first_name = 'Paul', last_name = 'Exemple' WHERE id = ?", dm);

		assertThat(accounts.fullName(world.schoolX, dm)).contains("Paul Exemple");
	}

	@Test
	void fullNameOfAUserOfAnotherSchoolIsEmpty() {
		assertThat(accounts.fullName(world.schoolY, world.user(DM_1))).isEmpty();
	}

}
